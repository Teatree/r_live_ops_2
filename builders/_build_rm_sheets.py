def newest_workbook():
    best, bn = None, -1
    for p in glob.glob(os.path.join(ROOT, 'workbooks', '*LIVE_OPS_V3*.xlsx')):
        m = re.search(r'\((\d+)\)\.xlsx$', p)
        n = int(m.group(1)) if m else 0
        if n > bn:
            best, bn = p, n
    return best


def unwrap(f):
    """=IFERROR(__xludf.DUMMYFUNCTION("<f>"), cached) -> =<f>; anything else unchanged."""
    if not isinstance(f, str) or DUMMY not in f:
        return f
    i, out = f.index(DUMMY) + len(DUMMY), []
    while i < len(f):
        ch = f[i]
        if ch == '"':
            if i + 1 < len(f) and f[i + 1] == '"':
                out.append('"')
                i += 2
                continue
            break
        out.append(ch)
        i += 1
    return '=' + ''.join(out)


def in_block(r, c):
    return BLOCK[1] <= r <= BLOCK[3] and CI(BLOCK[0]) <= c <= CI(BLOCK[2])


def copy_sheet(src, dst):
    n_unwrapped = 0
    for row in src.iter_rows():
        for c in row:
            if in_block(c.row, c.column):
                continue                              # the old block: rewritten below
            v = c.value
            if isinstance(v, ArrayFormula):
                t = unwrap(v.text)
                n_unwrapped += (t != v.text)
                v = ArrayFormula(ref=v.ref, text=t)
            elif isinstance(v, str):
                t = unwrap(v)
                n_unwrapped += (t != v)
                v = t
            if v is None and not c.has_style:
                continue
            d = dst.cell(row=c.row, column=c.column, value=v)
            if c.has_style:
                d.font, d.fill, d.border = copy(c.font), copy(c.fill), copy(c.border)
                d.alignment, d.number_format, d.protection = copy(c.alignment), c.number_format, copy(c.protection)
    for k, dim in src.column_dimensions.items():
        dst.column_dimensions[k].width = dim.width
        dst.column_dimensions[k].hidden = dim.hidden
    for k, dim in src.row_dimensions.items():
        if dim.height is not None:
            dst.row_dimensions[k].height = dim.height
    for rng in src.merged_cells.ranges:
        dst.merge_cells(str(rng))
    for cf in src.conditional_formatting:
        for rule in cf.rules:
            dst.conditional_formatting.add(str(cf.sqref), rule)
    for dv in src.data_validations.dataValidation:
        dst.add_data_validation(copy(dv))
    dst.sheet_view.showGridLines = src.sheet_view.showGridLines
    dst.freeze_panes = src.freeze_panes
    return n_unwrapped


def write_block(ws, config):
    f = lambda **k: Font(name=ARIAL, **k)
    for cell, val, kind in LS.block():
        if cell == 'AJ4':
            val = config
        c = ws[cell]
        c.value = val
        c.font = f(bold=(kind in ('title', 'header')), size=(11 if kind == 'title' else 10))
        if kind == 'input':
            c.fill = LS.IN_FILL
        elif kind in ('formula', 'pct'):
            c.fill = LS.SIM_FILL
            if kind == 'pct':
                c.number_format = '0.0%'
        elif kind == 'header':
            c.fill = LS.HDR_FILL
    for cell, opts in (('AJ2', '"p10,p25,p50,p75,p90,Avg"'), ('AJ3', '"NONPAYER,PAYER"'), ('AJ4', '"RM_1st,RM_2nd"')):
        dv = DataValidation(type='list', formula1=opts, allow_blank=False)
        ws.add_data_validation(dv)
        dv.add(cell)


def ladder(ws):
    """Req Accum of the milestones the ENGINE reads: rows 16.. down to the first non-number in column A."""
    reqs = []
    for r in range(16, 46):
        a = ws.cell(row=r, column=1).value
        if not isinstance(a, (int, float)) or isinstance(a, bool):
            break
        reqs.append(float(ws.cell(row=r, column=3).value or 0))
    return reqs


def emulate(wb, reqs, days, payer='NONPAYER', pct='p50'):
    """What AJ6:AR12 and row 13 should show for a ladder: the formulas' rule, in Python, on the workbook's own
    data_rm_pace (cached values)."""
    v = [list(r) for r in wb['data_rm_pace'].iter_rows(values_only=True)]
    h = {str(x).strip(): i for i, x in enumerate(v[0]) if x is not None}
    rows = [r for r in v[1:] if r and r[0] is not None and str(r[h['payer_flag']]).strip() == payer
            and ('resource' not in h or str(r[h['resource']]).strip() == 'ALL')]
    out, done = {}, {}
    for seg in LS.SEGS:
        rs = [r for r in rows if str(r[h['segment']]).strip() == seg]
        if not rs:
            continue
        ls = max(int(float(r[h['instance_length_days']])) for r in rs)
        q = {}
        for r in rs:
            if int(float(r[h['instance_length_days']])) == ls:
                q.setdefault(int(float(r[h['instance_day']])), []).append(r)
        qq = lambda dte, k: (sum(float(r[h[k]]) for r in q.get(dte, [])) / len(q[dte])) if q.get(dte) else 0.0
        per = []
        for d in range(1, days + 1):
            dte = ls if (d >= days and days >= ls - 1) else min(d, ls)
            p25, p50, p75, avg = (qq(dte, 'cum_matchables_' + s) for s in ('p25', 'p50', 'p75', 'mean'))
            top = max(p75, 8 * avg - 2 * (p25 + p50 + p75))
            mat = {'p25': p25, 'p50': p50, 'p75': p75, 'Avg': avg}[pct]
            per.append(sum(1 for x in reqs if x <= mat))
        out[seg] = per
        dte = ls if days >= ls - 1 else min(days, ls)
        p25, p50, p75, avg = (qq(dte, 'cum_matchables_' + s) for s in ('p25', 'p50', 'p75', 'mean'))
        top, x = max(p75, 8 * avg - 2 * (p25 + p50 + p75)), (reqs[-1] if reqs else 0)
        if x <= 0: u = 0
        elif x <= p25: u = 0.25 * x / max(p25, 1e-9)
        elif x <= p50: u = 0.25 + 0.25 * (x - p25) / max(p50 - p25, 1e-9)
        elif x <= p75: u = 0.5 + 0.25 * (x - p50) / max(p75 - p50, 1e-9)
        elif x <= top: u = 0.75 + 0.25 * (x - p75) / max(top - p75, 1e-9)
        else: u = 1
        done[seg] = 1 - u
    return out, done


