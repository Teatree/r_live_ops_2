"""Builds display/RM_Sheets_v1.xlsx (2026-11-03): the four Rainbow Maker config sheets - RM_1st, RM_2nd, RM_1st_v2,
RM_2nd_v2 - copied from the newest LIVE_OPS_V3 workbook with their current config, and the local "Player Reach
Simulation" block already replaced by the data_rm_pace version (v3 of RM_local_sim_formula.md, generated by
builders/_build_rm_localsim.py). So there is nothing to paste: import the four tabs over the old ones.

What is copied, cell for cell: every value and formula (the ladders, the Chest check in column D, levels req in AB, the
v2 helper blocks AC / AE:AG and the polynomial panel AI15:AJ19), array formulas, styles, column widths, row heights,
conditional formatting and data validation. Google writes a Sheets-only formula into an xlsx export as
=IFERROR(__xludf.DUMMYFUNCTION("<formula>"), <cached value>); those are unwrapped back to <formula>.

What changes: AI1:AS13 only. The old block (data_RM percentiles, 'SIMULATED') is cleared and the v3 block written in
its place - every data_rm_pace column found by its header, day d of an instance = date d of the measured event, the
last day of an instance as long as the measured one = its closing date (the engine's D77 rule, rmLive_), milestones
counted the way the engine reads the ladder (rows 16.. to the first non-number in column A). AJ4 is set per sheet
(RM_1st on the two first-half sheets, RM_2nd on the two second-half sheets); AJ2 / AJ3 get dropdowns.

    python builders/_build_rm_sheets.py [--workbook "workbooks/<file>.xlsx"] [--out display/RM_Sheets_v1.xlsx]
"""
